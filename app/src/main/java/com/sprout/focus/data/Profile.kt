package com.sprout.focus.data

import android.content.Context

/**
 * Как приложение обращается к человеку.
 *
 * Нужен ровно затем, чтобы не говорить «начнёшь ты сама» тому, кто «сам».
 * Всё остальное — возраст, пол как таковой, что угодно ещё — приложение
 * не спрашивает: поле, которым нечего менять, это требование без ответа.
 */
enum class Gender {
    /** «ты сама», «ты оставила» */
    FEMININE,

    /** «ты сам», «ты оставил» */
    MASCULINE,

    /**
     * Не сказал(а) — и не надо.
     *
     * Тогда приложение говорит безлично: не «начнёшь ты сама», а
     * «начинать тебе». Это не запасной вариант на крайний случай,
     * а обычный: пропустить знакомство — законный выбор.
     */
    UNKNOWN;

    companion object {
        fun of(raw: String?): Gender = entries.firstOrNull { it.name == raw } ?: UNKNOWN
    }
}

/**
 * Показывать ли знакомство и в каком виде.
 *
 * Три состояния вместо «да/нет» потому, что ответ зависит от базы, а она
 * отвечает не мгновенно. Показать сначала первую страницу и через миг
 * перескочить на четвёртую — хуже, чем не показать ничего.
 */
enum class WelcomeMode {
    /** Ещё считаем. Бывает только в первый запуск после установки или обновления. */
    UNKNOWN,

    /** Знакомство уже было. Обычное состояние, известно синхронно. */
    NONE,

    /** Приложение видят впервые: три страницы про замысел и вопрос об имени. */
    FULL,

    /** Приложением уже пользуются: только вопрос об имени, он в этой версии новый. */
    NAME_ONLY,
}

/**
 * Голос приложения: имя человека и форма обращения.
 *
 * Живёт отдельно от экранов, чтобы одну и ту же фразу можно было проверить
 * тестом во всех трёх видах. Тон при этом не меняется: словарь запрещённых
 * слов действует одинаково и для «сама», и для «сам», и для безличного.
 */
data class Voice(
    val name: String? = null,
    val gender: Gender = Gender.UNKNOWN,
) {
    /**
     * Выбрать форму фразы.
     *
     * Безличный вариант обязателен и пишется первым по важности: им
     * приложение говорит с каждым, кто не стал заполнять знакомство.
     */
    fun say(feminine: String, masculine: String, neutral: String): String = when (gender) {
        Gender.FEMININE -> feminine
        Gender.MASCULINE -> masculine
        Gender.UNKNOWN -> neutral
    }

    /** «Марина, » — или пусто, если имени нет. Пустое имя не заменяем на «друг». */
    val address: String get() = name?.takeIf { it.isNotBlank() }?.let { "$it, " }.orEmpty()

    /** Имя с заглавной для заголовков: «Привет, Марина». */
    val nameOrNull: String? get() = name?.takeIf { it.isNotBlank() }

    val isKnown: Boolean get() = nameOrNull != null || gender != Gender.UNKNOWN

    /**
     * Обратиться по имени: «Что мешает?» → «Марина, что мешает?».
     *
     * Одним методом, а не склейкой на каждом экране: без имени фраза должна
     * остаться ровно такой, какой написана, — с заглавной и без висящей
     * запятой. Склеенное вручную в трёх местах разъезжается при первой же
     * правке, а человек читает это каждый день.
     */
    fun ask(sentence: String): String =
        if (address.isEmpty()) sentence
        else address + sentence.replaceFirstChar { it.lowercase() }
}

/**
 * Фразы, у которых есть род.
 *
 * Живут здесь, а не в экранах, по двум причинам. Во-первых, безличный
 * вариант — обещание, которое надо проверять: «сама» и «сам», забытые
 * в нём, увидит ровно тот человек, который пола не называл. Из экрана
 * его тестом не достать, отсюда — достать.
 *
 * Во-вторых, их мало, и это не случайность: почти везде безличная
 * формулировка просто лучше. Три формы одной фразы — три текста,
 * которые надо держать в согласии.
 */
object Phrases {

    /** Под полем «если», когда напоминания не будет: начинать всё равно человеку. */
    fun startIsOnYou(voice: Voice): String = voice.say(
        feminine = "План будет на виду в задаче, а начнёшь ты сама.",
        masculine = "План будет на виду в задаче, а начнёшь ты сам.",
        neutral = "План будет на виду в задаче, а начинать тебе.",
    )

    /** Почему поле плана обязательное: так осталось после эксперимента. */
    fun planKept(voice: Voice): String = voice.say(
        feminine = "Обязательное поле: ты оставила так после эксперимента.",
        masculine = "Обязательное поле: ты оставил так после эксперимента.",
        neutral = "Обязательное поле: так осталось после эксперимента.",
    )

    /** Все фразы с родом — для проверки, что безличный вариант безличен. */
    fun all(voice: Voice): List<String> = listOf(startIsOnYou(voice), planKept(voice))
}

/**
 * Профиль в настройках, а не в базе.
 *
 * Это не событие и не данные о том, что человек делал, — это одна строка
 * и один переключатель, которые он про себя сказал. Заодно они попадают
 * в копию данных вместе с остальными настройками.
 */
class ProfileRepository(context: Context) {

    private val prefs = context.getSharedPreferences("profile", Context.MODE_PRIVATE)

    var voice: Voice
        get() = Voice(
            name = prefs.getString(KEY_NAME, null),
            gender = Gender.of(prefs.getString(KEY_GENDER, null)),
        )
        set(value) = prefs.edit()
            .putString(KEY_NAME, value.name?.trim()?.takeIf { it.isNotEmpty() })
            .putString(KEY_GENDER, value.gender.name)
            .apply()

    /**
     * Знакомство показано.
     *
     * Отдельно от заполненности профиля: человек мог пройти знакомство
     * и не назвать имени. Спрашивать второй раз — значит не услышать
     * первый отказ.
     */
    var metPerson: Boolean
        get() = prefs.getBoolean(KEY_MET, false)
        set(value) = prefs.edit().putBoolean(KEY_MET, value).apply()

    companion object {
        const val KEY_NAME = "name"
        const val KEY_GENDER = "gender"
        const val KEY_MET = "met"
    }
}
